let sortOrderPosts = 'desc';
function toggleSortOrder() {
    const t = fullTranslations[currentLangFull];
    if (!allPosts || allPosts.length === 0) return;
    sortOrderPosts = sortOrderPosts === 'desc' ? 'asc' : 'desc';
    allPosts.sort((a, b) => {
        const dateA = a.timestamp ? a.timestamp.toDate() : new Date(0);
        const dateB = b.timestamp ? b.timestamp.toDate() : new Date(0);
        return sortOrderPosts === 'desc' ? dateB - dateA : dateA - dateB;
    });
    renderPosts(allPosts);
    alert(sortOrderPosts === 'desc' ? "📅 Eng yangidan eskiga" : "📅 Eskidan yangiga");
}

