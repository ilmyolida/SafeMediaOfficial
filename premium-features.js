// Hozirgi tilni olish
let currentLangFull = localStorage.getItem('lang') || 'ky';

function updateAllTextsFull() {
    const t = fullTranslations[currentLangFull];
    if (!t) return;
    
    // Barcha data-lang-full atributli elementlarni yangilash
    document.querySelectorAll('[data-lang-full]').forEach(el => {
        const key = el.getAttribute('data-lang-full');
        if (t[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = t[key];
            } else if (el.tagName !== 'SELECT') {
                el.innerHTML = t[key];
            }
        }
    });
}

function changeLanguageFull(lang) {
    currentLangFull = lang;
    localStorage.setItem('lang', lang);
    updateAllTextsFull();
    // Sahifani qayta yuklamasdan tilni o'zgartirish
    if (typeof currentPage !== 'undefined') {
        if (currentPage === 'home') renderHomePage();
        else if (currentPage === 'profile') showProfilePage();
        else if (currentPage === 'info') renderInfoPage();
        else if (currentPage === 'community') renderCommunityPage();
    }
}

// ================= 2. MODAL OYNA FUNKSIYASI =================
let currentModal = null;

function showModal(content, title = "Safe Media") {
    closeModal();
    const modalDiv = document.createElement('div');
    modalDiv.id = 'customModal';
    modalDiv.className = 'modal';
    modalDiv.style.display = 'flex';
    modalDiv.innerHTML = `
        <div class="modal-content" style="max-width: 500px; max-height: 80vh; overflow-y: auto;">
            <span class="close-modal" onclick="closeModal()">&times;</span>
            <h3 style="margin-bottom: 15px;">${title}</h3>
            <div id="modalContent">${content}</div>
        </div>
    `;
    document.body.appendChild(modalDiv);
    currentModal = modalDiv;
}

function closeModal() {
    if (currentModal) {
        currentModal.remove();
        currentModal = null;
    }
}

// ================= 3. POSTLARNI SAQLASH VA BOSHQARISH =================
function savePostsToLocal() {
    if (!allPosts || allPosts.length === 0) {
        alert(fullTranslations[currentLangFull]?.noPosts || "No posts to save");
        return;
    }
    localStorage.setItem('safeMedia_backup', JSON.stringify(allPosts));
    alert("✅ " + (fullTranslations[currentLangFull]?.success || "Success!"));
}

function loadPostsFromLocal() {
    const data = localStorage.getItem('safeMedia_backup');
    if (!data) {
        alert("⚠️ " + (fullTranslations[currentLangFull]?.error || "No backup found"));
        return;
    }
    if (confirm(fullTranslations[currentLangFull]?.restore + "?")) {
        allPosts = JSON.parse(data);
        renderPosts(allPosts);
        alert("✅ " + (fullTranslations[currentLangFull]?.success || "Done!"));
    }
}

function sharePost(title, content) {
    const text = `${title}\n\n${content}\n\n— Safe Media`;
    if (navigator.share) {
        navigator.share({ title: title, text: content });
    } else {
        navigator.clipboard.writeText(text);
        alert("📋 " + (fullTranslations[currentLangFull]?.success || "Copied!"));
    }
}

function exportToPDF() {
    if (!allPosts || allPosts.length === 0) {
        alert(fullTranslations[currentLangFull]?.noPosts || "No posts");
        return;
    }
    let html = `<html><head><meta charset="UTF-8"><title>Safe Media Posts</title>
    <style>body{font-family:Arial;padding:20px} .post{border:1px solid #ddd;margin:10px 0;padding:15px;border-radius:10px}</style>
    </head><body><h1>Safe Media - All Posts</h1><p>Date: ${new Date().toLocaleDateString()}</p><hr>`;
    allPosts.forEach(post => {
        html += `<div class="post"><h3>${escapeHtml(post.title)}</h3>${post.imageUrl ? `<img src="${post.imageUrl}" style="max-width:100%">` : ''}<p>${escapeHtml(post.content)}</p></div>`;
    });
    html += `</body></html>`;
    const blob = new Blob([html], {type: 'text/html'});
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `safe_media_posts_${Date.now()}.html`;
    a.click();
    URL.revokeObjectURL(url);
}

